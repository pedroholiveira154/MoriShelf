function pesquisar() {
    const input = document.getElementById('pesquisar');

    input.addEventListener('keydown', function (event) {
        if (event.key === 'Enter') {
            event.preventDefault(); // Impede o envio padrão
            // Envia o formulário usando JavaScript
            input.submit();
        }
    });

}




